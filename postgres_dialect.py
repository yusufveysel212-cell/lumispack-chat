"""Translate the small, explicit SQLite SQL surface used by LUMISPAC.

This module is a PostgreSQL-port foundation, not a PostgreSQL storage adapter.
Driver connections must handle PRAGMA metadata separately and must reject every
statement this translator does not know how to make portable.
"""
import re


class UnsupportedSqlDialect(ValueError):
    """Raised instead of silently sending SQLite-only SQL to PostgreSQL."""


_REPLACE_KEYS = {"app_metadata": ("key",)}


def _qmark_to_format(sql):
    """Convert DB-API qmark parameters without touching quoted text/comments."""
    out = []
    i = 0
    state = "normal"
    while i < len(sql):
        char = sql[i]
        nxt = sql[i + 1] if i + 1 < len(sql) else ""
        if state == "normal":
            if char == "'":
                state = "single"
            elif char == '"':
                state = "double"
            elif char == "-" and nxt == "-":
                state = "line_comment"
            elif char == "/" and nxt == "*":
                state = "block_comment"
            elif char == "?":
                out.append("%s")
                i += 1
                continue
        elif state == "single" and char == "'":
            if nxt == "'":
                out.extend((char, nxt))
                i += 2
                continue
            state = "normal"
        elif state == "double" and char == '"':
            if nxt == '"':
                out.extend((char, nxt))
                i += 2
                continue
            state = "normal"
        elif state == "line_comment" and char in "\r\n":
            state = "normal"
        elif state == "block_comment" and char == "*" and nxt == "/":
            out.extend((char, nxt))
            i += 2
            state = "normal"
            continue
        out.append(char)
        i += 1
    return "".join(out)


def _translate_replace(sql):
    match = re.match(
        r"^(\s*)INSERT\s+OR\s+REPLACE\s+INTO\s+([\w\"]+)\s*\(([^)]*)\)(.*)$",
        sql, flags=re.IGNORECASE | re.DOTALL,
    )
    if not match:
        return sql
    prefix, table, columns_text, tail = match.groups()
    normalized_table = table.strip('"').lower()
    keys = _REPLACE_KEYS.get(normalized_table)
    if not keys:
        raise UnsupportedSqlDialect(
            "INSERT OR REPLACE için conflict key tanımlı değil: %s" % normalized_table
        )
    columns = [column.strip().strip('"') for column in columns_text.split(",")]
    updates = [column for column in columns if column.lower() not in {k.lower() for k in keys}]
    if not updates:
        conflict = " ON CONFLICT (%s) DO NOTHING" % ", ".join(keys)
    else:
        assignments = ", ".join('"%s" = EXCLUDED."%s"' % (c, c) for c in updates)
        conflict = " ON CONFLICT (%s) DO UPDATE SET %s" % (
            ", ".join('"%s"' % key for key in keys), assignments
        )
    return "%sINSERT INTO %s (%s)%s%s" % (prefix, table, columns_text, tail, conflict)


def _translate_schema_catalog(sql):
    table_query = re.compile(
        r"\bSELECT\s+1\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'\s+AND\s+name\s*=\s*(\?|(?:'[^']*'))",
        re.IGNORECASE,
    )
    sql = table_query.sub(
        r"SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = \1",
        sql,
    )
    list_query = re.compile(
        r"\bSELECT\s+name\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'"
        r"(?:\s+AND\s+name\s*=\s*(\?|(?:'[^']*')))?",
        re.IGNORECASE,
    )
    return list_query.sub(
        lambda m: "SELECT table_name AS name FROM information_schema.tables "
                  "WHERE table_schema = current_schema()" +
                  (" AND table_name = " + m.group(1) if m.group(1) else ""),
        sql,
    )


def translate_sql(sql):
    """Translate supported SQL; reject SQLite-only constructs needing a handler."""
    if not isinstance(sql, str):
        raise TypeError("SQL statement must be text")
    statement = sql.strip()
    if re.match(r"PRAGMA\b", statement, re.IGNORECASE):
        raise UnsupportedSqlDialect("PRAGMA PostgreSQL adaptöründe açıkça uygulanmalı.")
    if re.search(r"\browid\b|\bsqlite_sequence\b", statement, re.IGNORECASE):
        raise UnsupportedSqlDialect("rowid/sqlite_sequence PostgreSQL'de desteklenmiyor.")
    statement = re.sub(r"^BEGIN\s+IMMEDIATE\b", "BEGIN", statement,
                       count=1, flags=re.IGNORECASE)
    statement = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        statement, flags=re.IGNORECASE,
    )
    if re.match(r"^(CREATE\s+TABLE|ALTER\s+TABLE)\b", statement, re.IGNORECASE):
        # SQLite's dynamic REAL/INTEGER storage must not narrow values during
        # PostgreSQL transfer (REAL alone would become float4 in PostgreSQL).
        statement = re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement,
                           flags=re.IGNORECASE)
        statement = re.sub(r"\bINTEGER\b", "BIGINT", statement,
                           flags=re.IGNORECASE)
    statement = _translate_replace(statement)
    ignored = re.match(r"^(\s*)INSERT\s+OR\s+IGNORE\s+INTO\b", statement,
                       flags=re.IGNORECASE)
    if ignored:
        statement = re.sub(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b",
                           "INSERT INTO", statement, count=1, flags=re.IGNORECASE)
        statement = statement.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    statement = _translate_schema_catalog(statement)
    return _qmark_to_format(statement)
